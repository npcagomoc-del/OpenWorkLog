import { test, expect } from '@playwright/test';
import { openBlankWorkspace } from './workspace';

test('a plan timer updates its existing daily entry without losing planned times', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-21T05:10:00Z'));
  await openBlankWorkspace(page);
  await page.goto('/calendar');
  await page.getByRole('button', { name: 'New plan', exact: true }).click();
  const plan = page.getByRole('dialog', { name: 'Plan your time' });
  await plan.getByLabel('Plan title', { exact: true }).fill('Planned camera review');
  await plan.getByLabel('From', { exact: true }).fill('13:00');
  await plan.getByLabel('To', { exact: true }).selectOption({ label: '14:00' });
  await plan.getByRole('button', { name: 'Save plan', exact: true }).click();
  await expect(plan).toBeHidden();
  await page.locator('.calendar-agenda-item').filter({ hasText: 'Planned camera review' }).click();
  const detail = page.getByRole('dialog', { name: 'Planned camera review', exact: true });
  await detail.getByRole('button', { name: 'Log work from this plan', exact: true }).click();
  const entry = page.getByRole('dialog', { name: 'Edit daily entry' });
  await expect(entry).toBeVisible();
  const originalEntryId = new URL(page.url()).searchParams.get('entry');
  expect(originalEntryId).toBeTruthy();
  await entry.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.goto('/calendar');
  await page.locator('.calendar-agenda-item').filter({ hasText: 'Planned camera review' }).click();
  await detail.getByRole('button', { name: 'Start timer now', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeVisible();
  await page.clock.setFixedTime(new Date('2026-10-21T05:42:00Z'));
  await page.getByRole('button', { name: 'Stop and review', exact: true }).click();
  const review = page.getByRole('dialog', { name: 'Review your session' });
  await review.getByLabel('Work done', { exact: true }).fill('Verified all camera angles.');
  await review.getByRole('button', { name: 'Save work log', exact: true }).click();
  await expect(review).toBeHidden();
  await expect(page.locator('.daily-summary .card').filter({ hasText: 'Daily tasks' }).locator('strong')).toHaveText('1');
  await page.goto('/calendar');
  await page.locator('.calendar-agenda-item').filter({ hasText: 'Planned camera review' }).click();
  await detail.getByRole('button', { name: 'Open daily entry', exact: true }).click();
  await expect(entry).toBeVisible();
  expect(new URL(page.url()).searchParams.get('entry')).toBe(originalEntryId);
  await expect(entry.getByLabel('Planned from', { exact: true })).toHaveValue('13:00');
  await expect(entry.getByLabel('Planned to', { exact: true })).toHaveValue('14:00');
  await expect(entry.getByLabel('Actual from', { exact: true })).toHaveValue('13:10');
  await expect(entry.getByLabel('Actual to', { exact: true })).toHaveValue('13:42');
  await expect(entry.getByLabel('Work done', { exact: true })).toHaveValue('Verified all camera angles.');
  await entry.getByLabel('Actual from', { exact: true }).fill('13:20');
  await entry.getByLabel('Actual to', { exact: true }).fill('13:30');
  await entry.getByRole('button', { name: 'Save entry', exact: true }).click();
  await expect(entry).toBeHidden();
  await expect(page.locator('.daily-summary .card').filter({ hasText: 'Productive time' }).locator('strong')).toHaveText('10m');
  await page.clock.setFixedTime(new Date('2026-10-21T05:50:00Z'));
  await page.goto('/calendar');
  await page.locator('.calendar-agenda-item').filter({ hasText: 'Planned camera review' }).click();
  await detail.getByRole('button', { name: 'Start timer now', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeVisible();
  await page.clock.setFixedTime(new Date('2026-10-21T06:00:00Z'));
  await page.getByRole('button', { name: 'Stop and review', exact: true }).click();
  await review.getByLabel('Work done', { exact: true }).fill('Checked follow-up recording.');
  await review.getByRole('button', { name: 'Save work log', exact: true }).click();
  await expect(review).toBeHidden();
  await expect(page.locator('.daily-summary .card').filter({ hasText: 'Daily tasks' }).locator('strong')).toHaveText('1');
  await expect(page.locator('.daily-summary .card').filter({ hasText: 'Productive time' }).locator('strong')).toHaveText('20m');
  await page.goto('/calendar');
  await page.locator('.calendar-agenda-item').filter({ hasText: 'Planned camera review' }).click();
  await detail.getByRole('button', { name: 'Open daily entry', exact: true }).click();
  await expect(entry).toBeVisible();
  expect(new URL(page.url()).searchParams.get('entry')).toBe(originalEntryId);
  await expect(entry.getByLabel('Work done', { exact: true })).toHaveValue(/Verified all camera angles\.[\s\S]*Checked follow-up recording\./);
  await expect(entry.getByLabel('Planned from', { exact: true })).toHaveValue('13:00');
  await expect(entry.getByLabel('Planned to', { exact: true })).toHaveValue('14:00');
});

