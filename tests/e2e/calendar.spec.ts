import { test, expect } from '@playwright/test';
import { createTask, openBlankWorkspace } from './workspace';

test('planner transfers task and project links into one daily entry with planned times', async ({ page }) => {
  await openBlankWorkspace(page);
  await page.goto('/projects');
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  const project = page.getByRole('dialog', { name: 'New project', exact: true });
  await project.getByLabel('Project name', { exact: true }).fill('Cabinet improvement');
  await project.getByRole('button', { name: 'Save project', exact: true }).click();
  await expect(project).toBeHidden();
  await createTask(page, 'Plan switch inspection');
  await page.getByRole('button', { name: 'Plan switch inspection', exact: true }).click();
  const task = page.getByRole('dialog', { name: 'Edit task', exact: true });
  await task.getByLabel('Parent project', { exact: true }).selectOption({ label: 'Cabinet improvement' });
  await task.getByRole('button', { name: 'Save task', exact: true }).click();
  await expect(task).toBeHidden();
  await page.goto('/calendar');
  await page.getByRole('button', { name: 'New plan', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Plan your time' });
  await editor.getByLabel('Linked task', { exact: true }).selectOption({ label: 'Plan switch inspection' });
  await expect(editor.getByLabel('Project', { exact: true }).locator('option:checked')).toHaveText('Cabinet improvement');
  await editor.getByLabel('From', { exact: true }).fill('09:00');
  await editor.getByLabel('To', { exact: true }).selectOption({ label: '10:00' });
  await editor.getByRole('button', { name: 'Save plan', exact: true }).click();
  await expect(editor).toBeHidden();
  await page.reload();
  await page.locator('.calendar-agenda-item').filter({ hasText: 'Plan switch inspection' }).click();
  const details = page.getByRole('dialog', { name: 'Plan switch inspection', exact: true });
  await details.getByRole('button', { name: 'Log work from this plan', exact: true }).click();
  const entry = page.getByRole('dialog', { name: 'Edit daily entry' });
  await expect(entry.getByLabel('Linked task / operational task', { exact: true }).locator('option:checked')).toHaveText('Plan switch inspection');
  await expect(entry.getByLabel('Planned from', { exact: true })).toHaveValue('09:00');
  await expect(entry.getByLabel('Planned to', { exact: true })).toHaveValue('10:00');
  await expect(entry.getByLabel('Actual from', { exact: true })).toHaveValue('');
  await entry.locator('summary').click();
  await expect(entry.getByLabel('Linked project', { exact: true }).locator('option:checked')).toHaveText('Cabinet improvement');
  await entry.getByLabel('Actual from', { exact: true }).fill('09:10');
  await entry.getByLabel('Actual to', { exact: true }).fill('09:45');
  await entry.getByLabel('Work done', { exact: true }).fill('Verified power and uplink.');
  await entry.getByRole('button', { name: 'Save entry', exact: true }).click();
  await expect(entry).toBeHidden();
  await page.goto('/calendar');
  await page.locator('.calendar-agenda-item').filter({ hasText: 'Plan switch inspection' }).click();
  await details.getByRole('button', { name: 'Open daily entry', exact: true }).click();
  await expect(entry.getByLabel('Work done', { exact: true })).toHaveValue('Verified power and uplink.');
  await entry.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.locator('.daily-summary .card').filter({ hasText: 'Daily tasks' }).locator('strong')).toHaveText('1');
});
