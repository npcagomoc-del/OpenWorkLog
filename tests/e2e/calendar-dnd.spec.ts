import { expect, test, type Page } from '@playwright/test';
import { openBlankWorkspace } from './workspace';

async function addPlan(page: Page, title: string) {
  await openBlankWorkspace(page);
  await page.goto('/calendar');
  await page.getByLabel('Go to date', { exact: true }).fill('2026-10-21');
  await page.getByRole('button', { name: 'New plan', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Plan your time' });
  await editor.getByLabel('Plan title', { exact: true }).fill(title);
  await editor.getByLabel('From', { exact: true }).fill('09:00');
  await editor.getByLabel('To', { exact: true }).selectOption({ label: '10:00' });
  await editor.getByRole('button', { name: 'Save plan', exact: true }).click();
  await expect(editor).toBeHidden();
}

test('calendar mouse drag moves one linked plan and its planned-only daily entry', async ({ page }, testInfo) => {
  await addPlan(page, 'Move switch inspection');
  await page.locator('.calendar-block-open').filter({ hasText: 'Move switch inspection' }).click();
  await page.getByRole('button', { name: 'Log work from this plan', exact: true }).click();
  const entry = page.getByRole('dialog', { name: 'Edit daily entry' });
  await expect(entry).toBeVisible();
  const entryId = new URL(page.url()).searchParams.get('entry');
  expect(entryId).toBeTruthy();
  await entry.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.goto('/calendar');
  await page.getByLabel('Go to date', { exact: true }).fill('2026-10-21');
  await expect(page.locator('[data-calendar-date="2026-10-21"][data-calendar-minute="540"]')).toBeDisabled();
  await expect(page.locator('[data-calendar-date="2026-10-21"][data-calendar-minute="570"]')).toBeDisabled();
  await expect(page.locator('[data-calendar-date="2026-10-21"][data-calendar-minute="600"]')).toBeEnabled();
  const handle = page.getByRole('button', { name: 'Move plan Move switch inspection', exact: true });
  const destination = page.locator('[data-calendar-date="2026-10-22"][data-calendar-minute="600"]');
  await destination.scrollIntoViewIfNeeded();
  const source = await handle.boundingBox();
  const target = await destination.boundingBox();
  expect(source).not.toBeNull();
  expect(target).not.toBeNull();
  if (!source || !target) return;
  await page.screenshot({ path: testInfo.outputPath('calendar-mouse-rest.png'), fullPage: true });
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2);
  await page.mouse.down();
  await page.mouse.move(source.x + source.width / 2 + 8, source.y + source.height / 2, { steps: 2 });
  await expect(page.locator('.calendar-drag-preview')).toBeVisible();
  await expect(page.locator('.calendar-block--dragging')).toHaveCSS('opacity', '1');
  await expect(page.locator('.calendar-drag-preview')).toHaveAttribute('aria-hidden', 'true');
  await page.mouse.move(target.x + target.width / 2, target.y + target.height / 2, { steps: 12 });
  await expect(destination).toHaveClass(/calendar-slot--drop/);
  await expect(destination).toHaveAccessibleName('Move here · 10:00, 2026-10-22');
  await page.screenshot({ path: testInfo.outputPath('calendar-mouse-active.png'), fullPage: true });
  await page.mouse.up();
  await expect(page.locator('.calendar-block-open')).toHaveAttribute('title', 'Move switch inspection · 10:00–11:00');
  await page.screenshot({ path: testInfo.outputPath('calendar-mouse-settled.png'), fullPage: true });
  await page.reload();
  await page.getByLabel('Go to date', { exact: true }).fill('2026-10-21');
  await expect(page.locator('.calendar-block-open')).toHaveAttribute('title', 'Move switch inspection · 10:00–11:00');
  await page.locator('.calendar-block-open').scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('calendar-mouse-moved.png'), fullPage: true });
  await page.goto(`/daily?date=2026-10-22&entry=${encodeURIComponent(entryId ?? '')}`);
  await expect(entry.getByLabel('Planned from', { exact: true })).toHaveValue('10:00');
  await expect(entry.getByLabel('Planned to', { exact: true })).toHaveValue('11:00');
  await expect(entry.getByLabel('Actual from', { exact: true })).toHaveValue('');
  await entry.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.goto('/tasks');
  await expect(page.getByRole('button', { name: 'Move switch inspection', exact: true })).toHaveCount(1);
});

test('calendar keyboard drag moves half-hour/day, restores focus and cancels without changes', async ({ page }) => {
  await addPlan(page, 'Keyboard plan');
  const handle = page.getByRole('button', { name: 'Move plan Keyboard plan', exact: true });
  await handle.scrollIntoViewIfNeeded();
  await handle.focus();
  await handle.press('Space', { delay: 50 });
  await expect(handle).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.calendar-drag-preview')).toBeVisible();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('ArrowRight');
  await expect(page.locator('.calendar-drag-help')).toContainText('2026-10-22 at 09:30');
  await page.keyboard.press('Enter');
  await expect(page.locator('.calendar-block-open')).toHaveAttribute('title', 'Keyboard plan · 09:30–10:30');
  await expect(handle).toBeFocused();
  await handle.press('Space', { delay: 50 });
  await expect(handle).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.calendar-drag-preview')).toBeVisible();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Escape');
  await expect(page.locator('.calendar-drag-preview')).toBeHidden();
  await expect(page.locator('.calendar-block-open')).toHaveAttribute('title', 'Keyboard plan · 09:30–10:30');
  await page.reload();
  await page.getByLabel('Go to date', { exact: true }).fill('2026-10-21');
  await expect(page.locator('.calendar-block-open')).toHaveAttribute('title', 'Keyboard plan · 09:30–10:30');
});

test.describe('calendar touch movement', () => {
  test.use({ hasTouch: true, isMobile: true, viewport: { width: 430, height: 932 } });
  test('holding the grip moves a plan without disabling normal calendar scrolling', async ({ page }, testInfo) => {
    await addPlan(page, 'Touch plan');
    await page.getByRole('button', { name: 'Day', exact: true }).click();
    const handle = page.getByRole('button', { name: 'Move plan Touch plan', exact: true });
    const destination = page.locator('[data-calendar-date="2026-10-21"][data-calendar-minute="630"]');
    await destination.scrollIntoViewIfNeeded();
    const source = await handle.boundingBox();
    const target = await destination.boundingBox();
    expect(source).not.toBeNull();
    expect(target).not.toBeNull();
    if (!source || !target) return;
    const session = await page.context().newCDPSession(page);
    await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: source.x + source.width / 2, y: source.y + source.height / 2 }] });
    await expect(page.locator('.calendar-drag-preview')).toBeVisible();
    await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: target.x + target.width / 2, y: target.y + target.height / 2 }] });
    await expect(destination).toHaveClass(/calendar-slot--drop/);
    await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    await expect(page.locator('.calendar-block-open')).toHaveAttribute('title', 'Touch plan · 10:30–11:30');
    await expect(handle).toHaveCSS('touch-action', 'none');
    await expect(page.locator('.calendar-slot').first()).not.toHaveCSS('touch-action', 'none');
    await page.reload();
  await page.getByLabel('Go to date', { exact: true }).fill('2026-10-21');
    await expect(page.locator('.calendar-block-open')).toHaveAttribute('title', 'Touch plan · 10:30–11:30');
    await page.getByRole('button', { name: 'Day', exact: true }).click();
    await page.locator('.calendar-block-open').scrollIntoViewIfNeeded();
    await page.screenshot({ path: testInfo.outputPath('calendar-touch-moved.png'), fullPage: true });
    await session.detach();
  });
});

test('calendar keeps duration through 24:00 and rejects a move past midnight', async ({ page }, testInfo) => {
  await addPlan(page, 'Late plan');
  await page.getByRole('button', { name: 'Day', exact: true }).click();
  await page.getByRole('checkbox', { name: /Work hours/ }).uncheck();
  await page.locator('.calendar-block-open').click();
  await page.getByRole('button', { name: 'Edit plan', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Edit plan', exact: true });
  await editor.getByLabel('From', { exact: true }).fill('22:30');
  await editor.getByLabel('To', { exact: true }).selectOption({ label: '23:30' });
  await editor.getByRole('button', { name: 'Save plan', exact: true }).click();
  await expect(editor).toBeHidden();
  const handle = page.getByRole('button', { name: 'Move plan Late plan', exact: true });
  await handle.scrollIntoViewIfNeeded();
  await handle.focus();
  await handle.press('Space', { delay: 50 });
  await expect(handle).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.calendar-drag-preview')).toBeVisible();
  await page.keyboard.press('ArrowDown');
  await expect(page.locator('.calendar-drag-help')).toContainText('at 23:00');
  await page.keyboard.press('Enter');
  await expect(page.locator('.calendar-block-open')).toHaveAttribute('title', 'Late plan · 23:00–24:00');
  await expect(handle).toBeFocused();
  await handle.press('Space', { delay: 50 });
  await expect(handle).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.calendar-drag-preview')).toBeVisible();
  await page.keyboard.press('ArrowDown');
  await expect(page.locator('.calendar-drag-help')).toContainText('at 23:30');
  await page.keyboard.press('Enter');
  await expect(page.getByRole('alert')).toContainText('This plan would end after midnight.');
  await expect(page.locator('.calendar-block-open')).toHaveAttribute('title', 'Late plan · 23:00–24:00');
  await page.screenshot({ path: testInfo.outputPath('calendar-midnight-protected.png'), fullPage: true });
  await page.reload();
  await page.getByLabel('Go to date', { exact: true }).fill('2026-10-21');
  await expect(page.locator('.calendar-agenda-item')).toContainText('23:00');
  await expect(page.locator('.calendar-agenda-item')).toContainText('24:00');
});
