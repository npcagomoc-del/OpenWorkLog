import { expect, test } from '@playwright/test';
import { openBlankWorkspace } from './workspace';

test('resize previews, cancels, saves linked bounds and survives reload', async ({ page }, testInfo) => {
  await openBlankWorkspace(page);
  await page.goto('/calendar');
  await page.getByLabel('Go to date', { exact: true }).fill('2026-10-21');
  await page.getByRole('button', { name: 'New plan', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Plan your time' });
  await editor.getByLabel('Plan title', { exact: true }).fill('Resize inspection');
  await editor.getByLabel('Business Unit / Requested for', { exact: true }).fill('Operations');
  await editor.getByLabel('From', { exact: true }).fill('09:00');
  await editor.getByLabel('To', { exact: true }).selectOption({ label: '10:00' });
  await editor.getByRole('button', { name: 'Save plan', exact: true }).click();
  await expect(editor).toBeHidden();
  const block = page.locator('.calendar-block-open').filter({ hasText: 'Resize inspection' });
  await block.click();
  await page.getByRole('button', { name: 'Log work from this plan', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Edit daily entry' })).toBeVisible();
  const entryId = new URL(page.url()).searchParams.get('entry');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.goto('/calendar');
  await page.getByLabel('Go to date', { exact: true }).fill('2026-10-21');
  await block.click();
  await expect(page.getByRole('dialog').locator('p').filter({ hasText: 'Operations' })).toBeVisible();
  await page.getByRole('button', { name: 'Edit plan', exact: true }).click();
  const edit = page.getByRole('dialog', { name: 'Edit plan', exact: true });
  await edit.getByLabel('Business Unit / Requested for', { exact: true }).fill('');
  await edit.getByRole('button', { name: 'Save plan', exact: true }).click();
  await expect(edit).toBeHidden();
  const end = page.getByRole('button', { name: 'Resize end of Resize inspection', exact: true });
  await end.focus();
  await end.press('ArrowDown');
  await expect(block).toContainText('09:00–10:30');
  await expect(page.locator('[data-calendar-date="2026-10-21"][data-calendar-minute="600"]')).toBeDisabled();
  await end.press('Escape');
  await expect(block).toContainText('09:00–10:00');
  await end.press('ArrowDown');
  await end.press('Enter');
  await expect(block).toHaveAttribute('title', 'Resize inspection · 09:00–10:30');
  await expect(end).toBeFocused();
  await page.getByRole('button', { name: 'Day', exact: true }).click();
  await block.hover();
  const source = await end.boundingBox();
  expect(source).not.toBeNull();
  if (!source) return;
  await page.mouse.move(source.x + 22, source.y + 22);
  await page.mouse.down();
  await page.mouse.move(source.x + 22, source.y - 34, { steps: 6 });
  await expect(block).toContainText('09:00–10:00');
  await page.screenshot({ path: testInfo.outputPath('resize-live.png'), fullPage: true });
  await page.mouse.up();
  await expect(block).toHaveAttribute('title', 'Resize inspection · 09:00–10:00');
  const start = page.getByRole('button', { name: 'Resize start of Resize inspection', exact: true });
  await start.focus();
  await start.press('ArrowDown');
  await start.press('Enter');
  await expect(block).toHaveAttribute('title', 'Resize inspection · 09:30–10:00');
  await page.getByRole('button', { name: 'Week', exact: true }).click();
  await start.focus();
  const geometry = await page.locator('.calendar-block').filter({ hasText: 'Resize inspection' }).evaluate((node) => {
    const start = node.querySelector('.calendar-resize-handle--start')?.getBoundingClientRect();
    const end = node.querySelector('.calendar-resize-handle--end')?.getBoundingClientRect();
    const move = node.querySelector('.calendar-drag-handle')?.getBoundingClientRect();
    return start && end && move ? { gap: end.top - start.bottom, startWidth: start.width, startHeight: start.height, endWidth: end.width, moveGap: move.left - start.right } : null;
  });
  expect(geometry).not.toBeNull();
  expect(geometry?.gap).toBeGreaterThanOrEqual(10);
  expect(geometry?.startWidth).toBe(44);
  expect(geometry?.startHeight).toBe(44);
  expect(geometry?.moveGap).toBeGreaterThanOrEqual(0);
  await page.screenshot({ path: testInfo.outputPath('resize-half-hour-selected.png'), fullPage: true });
  await start.press('ArrowUp');
  await start.press('Enter');
  await expect(block).toHaveAttribute('title', 'Resize inspection · 09:00–10:00');
  await end.focus();
  const cancelSource = await end.boundingBox();
  if (!cancelSource) throw new Error('Resize handle is missing');
  await page.mouse.move(cancelSource.x + 22, cancelSource.y + 22);
  await page.mouse.down();
  await page.mouse.move(cancelSource.x + 22, cancelSource.y + 78, { steps: 6 });
  await expect(block).toContainText('09:00–10:30');
  await expect(page.locator('[data-calendar-date="2026-10-21"][data-calendar-minute="600"]')).toBeDisabled();
  await page.keyboard.press('Escape');
  await page.mouse.up();
  await expect(block).toHaveAttribute('title', 'Resize inspection · 09:00–10:00');
  await page.getByRole('button', { name: 'New plan', exact: true }).click();
  await editor.getByLabel('Plan title', { exact: true }).fill('Adjacent plan');
  await editor.getByLabel('From', { exact: true }).fill('10:00');
  await editor.getByLabel('To', { exact: true }).selectOption({ label: '10:30' });
  await editor.getByRole('button', { name: 'Save plan', exact: true }).click();
  await expect(editor).toBeHidden();
  await end.focus();
  const adjacentStart = page.getByRole('button', { name: 'Resize start of Adjacent plan', exact: true });
  await expect(adjacentStart).toHaveCSS('pointer-events', 'none');
  await expect(page.getByRole('button', { name: 'Move plan Adjacent plan', exact: true })).toBeEnabled();
  await page.screenshot({ path: testInfo.outputPath('resize-adjacent-week.png'), fullPage: true });
  await page.reload();
  await page.getByLabel('Go to date', { exact: true }).fill('2026-10-21');
  await expect(block).toHaveAttribute('title', 'Resize inspection · 09:00–10:00');
  await block.click();
  await expect(page.getByRole('dialog').locator('p').filter({ hasText: 'Operations' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Edit plan', exact: true }).click();
  await expect(edit.getByLabel('Business Unit / Requested for', { exact: true })).toHaveValue('');
  await edit.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.goto(`/daily?date=2026-10-21&entry=${encodeURIComponent(entryId ?? '')}`);
  await expect(page.getByLabel('Planned to', { exact: true })).toHaveValue('10:00');
  await expect(page.getByLabel('Actual from', { exact: true })).toHaveValue('');
});



test.describe('touch resize', () => {
  test.use({ hasTouch: true, isMobile: true, viewport: { width: 430, height: 932 } });
  test('touch edge commits once and pointer cancellation restores the preview', async ({ page }, testInfo) => {
    await openBlankWorkspace(page);
    await page.goto('/calendar');
    await page.getByLabel('Go to date', { exact: true }).fill('2026-10-21');
    await page.getByRole('button', { name: 'New plan', exact: true }).click();
    const editor = page.getByRole('dialog', { name: 'Plan your time' });
    await editor.getByLabel('Plan title', { exact: true }).fill('Touch resize');
    await editor.getByLabel('From', { exact: true }).fill('09:00');
    await editor.getByLabel('To', { exact: true }).selectOption({ label: '10:00' });
    await editor.getByRole('button', { name: 'Save plan', exact: true }).click();
    await expect(editor).toBeHidden();
    await page.getByRole('button', { name: 'New plan', exact: true }).click();
    await editor.getByLabel('Plan title', { exact: true }).fill('Touch neighbor');
    await editor.getByLabel('From', { exact: true }).fill('10:00');
    await editor.getByLabel('To', { exact: true }).selectOption({ label: '10:30' });
    await editor.getByRole('button', { name: 'Save plan', exact: true }).click();
    await expect(editor).toBeHidden();
    await page.getByRole('button', { name: 'Day', exact: true }).click();
    await page.getByRole('button', { name: 'Move plan Touch resize', exact: true }).tap();
    await expect(page.getByRole('button', { name: 'Resize start of Touch neighbor', exact: true })).toHaveCSS('pointer-events', 'none');
    const end = page.getByRole('button', { name: 'Resize end of Touch resize', exact: true });
    await end.scrollIntoViewIfNeeded();
    const source = await end.boundingBox();
    if (!source) throw new Error('Missing touch resize handle');
    const cdp = await page.context().newCDPSession(page);
    const point = { x: source.x + 22, y: source.y + 22 };
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [point] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ ...point, y: point.y + 56 }] });
    await expect(page.locator('.calendar-block-open').filter({ hasText: 'Touch resize' })).toContainText('09:00–10:30');
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] });
    await expect(page.locator('.calendar-block-open').filter({ hasText: 'Touch resize' })).toContainText('09:00–10:00');
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [point] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ ...point, y: point.y + 56 }] });
    await expect(page.locator('.calendar-block-open').filter({ hasText: 'Touch resize' })).toContainText('09:00–10:30');
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    await expect(page.locator('.calendar-block-open').filter({ hasText: 'Touch resize' })).toHaveAttribute('title', 'Touch resize · 09:00–10:30');
    await page.screenshot({ path: testInfo.outputPath('touch-resize-saved.png'), fullPage: true });
    await page.reload();
    await page.getByLabel('Go to date', { exact: true }).fill('2026-10-21');
    await expect(page.locator('.calendar-block-open').filter({ hasText: 'Touch resize' })).toHaveAttribute('title', 'Touch resize · 09:00–10:30');
    await cdp.detach();
  });
});
